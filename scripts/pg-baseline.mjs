// Generates the initial PostgreSQL migration from the schema without needing a
// Postgres server (prisma migrate diff --from-empty). Run via
// `npm run db:migrations:pg`. Later schema changes should be created with
// `prisma migrate dev` against a real Postgres database.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";

const dir = "prisma/migrations/postgresql";
const tmpSchema = "prisma/schema.pg.tmp.prisma";

try {
  const existing = existsSync(dir) ? readdirSync(dir).filter((f) => f !== "migration_lock.toml") : [];
  if (existing.length > 0) {
    console.log(`${dir} already has migrations; create new ones with prisma migrate dev against Postgres.`);
    process.exit(0);
  }
  const sql = execFileSync(
    "npx",
    ["prisma", "migrate", "diff", "--from-empty", "--to-schema", tmpSchema, "--script"],
    { encoding: "utf8", shell: true },
  );
  const name = `${new Date().toISOString().replace(/\D/g, "").slice(0, 14)}_init`;
  mkdirSync(`${dir}/${name}`, { recursive: true });
  writeFileSync(`${dir}/${name}/migration.sql`, sql);
  writeFileSync(
    `${dir}/migration_lock.toml`,
    '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
  );
  console.log(`wrote ${dir}/${name}/migration.sql`);
} finally {
  rmSync(tmpSchema, { force: true });
}
