// Writes prisma/schema.prisma = datasource block + prisma/schema.base.prisma.
// Usage: node scripts/prisma-schema.mjs [--provider sqlite|postgresql] [--out path]
import { readFileSync, writeFileSync } from "node:fs";
import { loadEnv, providerFromUrl } from "./db-provider.mjs";

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
};

loadEnv();
const provider = flag("--provider") ?? providerFromUrl(process.env.DATABASE_URL);
const out = flag("--out") ?? "prisma/schema.prisma";

const header = `// GENERATED by scripts/prisma-schema.mjs — do not edit. Edit schema.base.prisma.

datasource db {
  provider = "${provider}"
}

`;

writeFileSync(out, header + readFileSync("prisma/schema.base.prisma", "utf8"));
console.log(`prisma schema written (${provider}) → ${out}`);
